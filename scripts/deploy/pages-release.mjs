#!/usr/bin/env node
// Production deploy package for GitHub Actions (push to main → Cloudflare Pages project sikap-v2).
//
// Why a separate release directory OUTSIDE the checkout: Wrangler resolves the nearest wrangler.toml
// by walking up from its cwd (and loads .env from it), and the root wrangler.toml still carries the
// HISTORICAL production bindings (sikap-db / sikap-files). Deploying with a config also rewrites the
// project's binding settings, so the rendered config mirrors the live project exactly (read with
// `wrangler pages download config sikap-v2` on 21 Oct 2026): preview bindings at the top level,
// production bindings in [env.production]. Only the production D1 database ID comes from the
// environment (GitHub secret PROD_D1_DATABASE_ID); it is never written to the repository.
//
// Usage (CI): PROD_D1_DATABASE_ID=… node scripts/deploy/pages-release.mjs "$RUNNER_TEMP/sikap-release"
// then run `wrangler pages deploy public --project-name sikap-v2 --branch main` inside that directory.
import { cp, lstat, mkdir, readdir, symlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const PROJECT_NAME = 'sikap-v2';
export const PRODUCTION = Object.freeze({
  appUrl: 'https://sikap.uptdpenda-kupang.web.id',
  d1Name: 'sikap-import-prod-20261020',
  r2Bucket: 'sikap-import-prod-20261020-files',
});
export const PREVIEW = Object.freeze({
  appUrl: 'https://feat-cloudflare-migration.sikap-v2.pages.dev',
  d1Name: 'sikap-db-preview',
  d1Id: '1bd39313-4072-43a7-a183-7544c8264c46',
  r2Bucket: 'sikap-files-preview',
});
/** Historical root bindings and the Access guard (custom domain must not require Access). */
export const DENIED = Object.freeze(['b8611b82-8067-4153-ae5e-d6a0b94be7a6', '"sikap-db"', '"sikap-files"', '"sikap-backup"', 'ACCESS_']);
/** Copied next to the static output so Wrangler can bundle Pages Functions (functions/ imports server/ and shared/). */
export const RELEASE_ENTRIES = Object.freeze(['functions', 'server', 'shared', 'package.json']);

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const WRANGLER_CONFIGS = ['wrangler.toml', 'wrangler.json', 'wrangler.jsonc'];
const fail = (code) => {
  throw new Error(code);
};

export function assertProductionD1Id(id) {
  if (typeof id !== 'string' || !UUID.test(id)) fail('PROD_D1_DATABASE_ID_INVALID');
  if (id === PREVIEW.d1Id || DENIED.some((ref) => ref.includes(id))) fail('PROD_D1_DATABASE_ID_DENIED');
  return id;
}

export function renderConfig(prodD1Id) {
  const id = assertProductionD1Id(prodD1Id);
  const text = `# GENERATED by scripts/deploy/pages-release.mjs: mirrors the live ${PROJECT_NAME} project settings.
name = "${PROJECT_NAME}"
pages_build_output_dir = "public"
compatibility_date = "2026-10-01"
compatibility_flags = ["nodejs_compat"]

[vars]
APP_URL = "${PREVIEW.appUrl}"
SESSION_TTL_HOURS = "12"

[[d1_databases]]
binding = "DB"
database_name = "${PREVIEW.d1Name}"
database_id = "${PREVIEW.d1Id}"

[[r2_buckets]]
binding = "FILES"
bucket_name = "${PREVIEW.r2Bucket}"

[env.production.vars]
APP_URL = "${PRODUCTION.appUrl}"
SESSION_TTL_HOURS = "12"

[[env.production.d1_databases]]
binding = "DB"
database_name = "${PRODUCTION.d1Name}"
database_id = "${id}"

[[env.production.r2_buckets]]
binding = "FILES"
bucket_name = "${PRODUCTION.r2Bucket}"
`;
  assertConfigSafe(text, id);
  return text;
}

/** Independent check of the rendered text: exact production bindings once, nothing historical. */
export function assertConfigSafe(text, prodD1Id) {
  const lines = text.split('\n');
  const once = (line) => lines.filter((l) => l === line).length === 1;
  const required = [
    `name = "${PROJECT_NAME}"`,
    '[env.production.vars]',
    `APP_URL = "${PRODUCTION.appUrl}"`,
    '[[env.production.d1_databases]]',
    `database_name = "${PRODUCTION.d1Name}"`,
    `database_id = "${prodD1Id}"`,
    '[[env.production.r2_buckets]]',
    `bucket_name = "${PRODUCTION.r2Bucket}"`,
  ];
  if (!required.every(once)) fail('RELEASE_CONFIG_PRODUCTION_BINDINGS');
  if (DENIED.some((ref) => text.includes(ref))) fail('RELEASE_CONFIG_DENIED_REF');
  // Two DB + two FILES bindings (preview + production); no BACKUPS, crons or other environments.
  if (lines.filter((l) => /^binding = /.test(l)).length !== 4) fail('RELEASE_CONFIG_BINDING_COUNT');
  if (/BACKUPS|\[triggers|crons|\[env\.(?!production)/.test(text)) fail('RELEASE_CONFIG_UNEXPECTED_SECTION');
}

function isInside(child, parent) {
  const rel = path.relative(parent, child);
  return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
}

async function exists(p) {
  try {
    await lstat(p);
    return true;
  } catch {
    return false;
  }
}

/** Builds the release directory: public/ (= dist), Functions sources, node_modules link, wrangler.toml. */
export async function prepareRelease({ root, outDir, prodD1Id }) {
  const config = renderConfig(prodD1Id);
  if (!path.isAbsolute(outDir)) fail('RELEASE_DIR_NOT_ABSOLUTE');
  const out = path.resolve(outDir);
  const repo = path.resolve(root);
  if (isInside(out, repo) || isInside(repo, out)) fail('RELEASE_DIR_INSIDE_CHECKOUT');
  // A config in any ancestor would be picked up by Wrangler instead of ours if ours went missing.
  for (let dir = path.dirname(out); ; dir = path.dirname(dir)) {
    for (const name of WRANGLER_CONFIGS) if (await exists(path.join(dir, name))) fail('RELEASE_DIR_ANCESTOR_CONFIG');
    if (path.dirname(dir) === dir) break;
  }
  if (await exists(out)) {
    if ((await readdir(out)).length > 0) fail('RELEASE_DIR_NOT_EMPTY');
  } else {
    await mkdir(out, { recursive: true });
  }

  const dist = path.join(repo, 'dist');
  if (!(await exists(path.join(dist, 'index.html')))) fail('BUILD_OUTPUT_MISSING');
  await cp(dist, path.join(out, 'public'), { recursive: true });
  for (const entry of RELEASE_ENTRIES) {
    const src = path.join(repo, entry);
    if (!(await exists(src))) fail(`RELEASE_SOURCE_MISSING:${entry}`);
    await cp(src, path.join(out, entry), { recursive: true });
  }
  for (const name of await readdir(repo)) {
    if (/^tsconfig.*\.json$/.test(name)) await cp(path.join(repo, name), path.join(out, name));
  }
  await symlink(path.join(repo, 'node_modules'), path.join(out, 'node_modules'), process.platform === 'win32' ? 'junction' : 'dir');
  await writeFile(path.join(out, 'wrangler.toml'), config, { flag: 'wx' });
  return out;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const outDir = process.argv[2];
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  try {
    if (!outDir) fail('USAGE: node scripts/deploy/pages-release.mjs <absolute-release-dir>');
    const out = await prepareRelease({ root, outDir, prodD1Id: process.env.PROD_D1_DATABASE_ID });
    console.log(`Release siap: ${out}`);
  } catch (error) {
    // Error codes only: never echo the configuration or the database ID.
    console.error(`pages-release: ${error instanceof Error ? error.message : 'UNKNOWN'}`);
    process.exit(1);
  }
}
