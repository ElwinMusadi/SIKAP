// DEV-ONLY seed: writes .wrangler/dev-seed.sql with fake users for local D1.
//   npm run db:seed:dev   (runs this, then `wrangler d1 execute sikap-db --local --file .wrangler/dev-seed.sql`)
//
// All data below is fictitious. Password = default (last 6 digits of NIP).
// Hashing MUST stay identical to server/lib/crypto.ts:
//   pbkdf2-sha256$<iter>$<salt_b64>$<hash_b64>, PBKDF2-SHA256(HMAC-SHA256(utf8(pepper), utf8(password)), salt16, 32 B)
// Idempotent: deletes the seeded NIPs (cascades to akun/sesi) before inserting.

import { webcrypto as crypto } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
