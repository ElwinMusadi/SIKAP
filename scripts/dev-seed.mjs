function readPepper() {
  const file = path.join(root, '.dev.vars');
  if (!existsSync(file)) {
    throw new Error('.dev.vars not found. Copy .dev.vars.example to .dev.vars first.');
  }
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*PASSWORD_PEPPER\s*=\s*(.*?)\s*$/.exec(line);
    if (!m) continue;
    let v = m[1];
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    if (!v) break;
    return v;
  }
  throw new Error('PASSWORD_PEPPER is missing or empty in .dev.vars');
}

const enc = new TextEncoder();
const b64 = (bytes) => Buffer.from(bytes).toString('base64');

async function hashPassword(password, pepper) {
  const hmacKey = await crypto.subtle.importKey('raw', enc.encode(pepper), { name: 'HMAC', hash: 'SHA-256' }, false, [
    'sign',
  ]);
  const peppered = await crypto.subtle.sign('HMAC', hmacKey, enc.encode(password));
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const key = await crypto.subtle.importKey('raw', peppered, 'PBKDF2', false, ['deriveBits']);
  const bits = await crypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations: ITERATIONS }, key, 256);
  return `pbkdf2-sha256$${ITERATIONS}$${b64(salt)}$${b64(new Uint8Array(bits))}`;
}

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

async function main() {
  const pepper = readPepper();
  const now = new Date().toISOString();
  const lines = [
    '-- GENERATED by scripts/dev-seed.mjs — DEV ONLY, fictitious data. Do not run against remote databases.',
    `DELETE FROM pegawai WHERE nip IN (${USERS.map((u) => q(u.nip)).join(', ')});`,
  ];
  for (const u of USERS) {
    const hash = await hashPassword(u.nip.slice(-6), pepper);
    lines.push(
      `INSERT INTO pegawai (nip, nama, role, status_akun, status_kepegawaian, pangkat_kode, jabatan, jenis_jabatan, unit_id, created_at, updated_at)
VALUES (${q(u.nip)}, ${q(u.nama)}, ${q(u.role)}, 'Aktif', ${q(u.statusKepegawaian)}, ${q(u.pangkat)}, ${q(u.jabatan)}, ${q(u.jenisJabatan)}, ${u.unitId}, ${q(now)}, ${q(now)});`,
      `INSERT INTO akun (pegawai_id, password_hash, is_default_password)
SELECT id, ${q(hash)}, 1 FROM pegawai WHERE nip = ${q(u.nip)};`,
    );
  }
  const outDir = path.join(root, '.wrangler');
  mkdirSync(outDir, { recursive: true });
  const outFile = path.join(outDir, 'dev-seed.sql');
  writeFileSync(outFile, lines.join('\n') + '\n', 'utf8');
  console.log(`Wrote ${path.relative(root, outFile)} (${USERS.length} dev users; password = last 6 digits of NIP).`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
